// Package tsgen writes TypeScript declarations for Go types, following
// encoding/json rules (field names from json tags, omitempty fields
// optional, embedded structs flattened), so the React frontend and the Go
// API cannot drift apart. cmd/tsgen lists the types; CI regenerates the
// file and fails if it changed.
package tsgen

import (
	"fmt"
	"io"
	"reflect"
	"sort"
	"strings"
	"time"
)

var timeType = reflect.TypeOf(time.Time{})
var durationType = reflect.TypeOf(time.Duration(0))

type gen struct {
	done  map[reflect.Type]string // type -> TS name
	queue []reflect.Type
}

// Write emits one exported TypeScript type per Go type in values (pass zero
// values, e.g. game.Board{}), plus every named struct type they reference.
func Write(w io.Writer, pkg string, values ...any) error {
	g := &gen{done: map[reflect.Type]string{}}
	for _, v := range values {
		g.name(reflect.TypeOf(v))
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by go run ./cmd/tsgen; DO NOT EDIT.\n// TypeScript types for the JSON that %s's Go code sends to the frontend.\n", pkg)
	// Declaring a type can queue the types it references, so drain until empty.
	decls := map[string]string{}
	for len(g.queue) > 0 {
		t := g.queue[0]
		g.queue = g.queue[1:]
		decls[g.done[t]] = g.decl(t)
	}
	names := make([]string, 0, len(decls))
	for n := range decls {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		out.WriteString("\n")
		out.WriteString(decls[n])
	}
	_, err := io.WriteString(w, out.String())
	return err
}

// name returns the TS type name for a named struct or string-like type,
// queueing its declaration.
func (g *gen) name(t reflect.Type) string {
	if n, ok := g.done[t]; ok {
		return n
	}
	n := t.Name()
	for _, other := range g.done {
		if other == n { // same name in two packages
			p := lastPath(t.PkgPath())
			n = strings.ToUpper(p[:1]) + p[1:] + n
		}
	}
	g.done[t] = n
	g.queue = append(g.queue, t)
	return n
}

func lastPath(p string) string { return p[strings.LastIndex(p, "/")+1:] }

func (g *gen) decl(t reflect.Type) string {
	if t.Kind() != reflect.Struct {
		return fmt.Sprintf("export type %s = %s;\n", g.done[t], g.expr(t, true))
	}
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", g.done[t])
	g.fields(&b, t)
	b.WriteString("}\n")
	return b.String()
}

func (g *gen) fields(b *strings.Builder, t reflect.Type) {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" || !f.IsExported() && !f.Anonymous {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Anonymous && name == "" {
			ft := f.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if ft.Kind() == reflect.Struct {
				g.fields(b, ft)
				continue
			}
		}
		if name == "" {
			name = f.Name
		}
		opt := strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero")
		ty := g.expr(f.Type, false)
		if strings.Contains(opts, "string") {
			ty = "string"
		}
		q := ""
		if opt {
			q = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, q, ty)
	}
}

// expr returns a TS type expression. top is true when declaring t itself.
func (g *gen) expr(t reflect.Type, top bool) string {
	switch {
	case t == timeType:
		return "string" // RFC 3339
	case t == durationType:
		return "number" // nanoseconds
	}
	if !top && t.Name() != "" && t.PkgPath() != "" && (t.Kind() == reflect.Struct || t.Kind() == reflect.String) {
		return g.name(t)
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.String:
		return "string"
	case reflect.Pointer:
		return g.expr(t.Elem(), false) + " | null"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string" // base64
		}
		return arr(g.expr(t.Elem(), false)) + " | null"
	case reflect.Array:
		return arr(g.expr(t.Elem(), false))
	case reflect.Map:
		return "Record<" + g.expr(t.Key(), false) + ", " + g.expr(t.Elem(), false) + ">"
	case reflect.Struct:
		var b strings.Builder
		b.WriteString("{\n")
		g.fields(&b, t)
		b.WriteString("}")
		return b.String()
	}
	return "unknown"
}

// arr writes T[] or (A | B)[] as needed.
func arr(elem string) string {
	if strings.ContainsAny(elem, " |{") {
		return "(" + elem + ")[]"
	}
	return elem + "[]"
}
